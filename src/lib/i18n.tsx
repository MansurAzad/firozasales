interface LangContextValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
}

const LangContext = createContext<LangContextValue>({
  lang: "bn",
  setLang: () => {},
  t: (key) => dict.bn[key] ?? key,
});

const LANG_KEY = "hisab-lang";

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("bn");

  // First render is always Bengali on both server and client; the stored or
  // phone preference is applied after hydration so there is no mismatch.
  useEffect(() => {
    const stored = window.localStorage.getItem(LANG_KEY);
    if (stored === "bn" || stored === "en") {
      setLangState(stored);
      return;
    }
    if (navigator.language.toLowerCase().startsWith("bn")) setLangState("bn");
    else setLangState("en");
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    window.localStorage.setItem(LANG_KEY, l);
  };

  const t = (key: string) => dict[lang][key] ?? dict.bn[key] ?? key;

  return (
    <LangContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LangContext.Provider>
  );
}

export const useLang = () => useContext(LangContext);
